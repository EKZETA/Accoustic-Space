"""Create a deterministic, class-balanced sample of an audio manifest."""

import argparse
import csv
import random
from pathlib import Path

project_root = Path(__file__).resolve().parents[1]
SPLITS = ("train", "dev", "eval")
LABELS = ("bonafide", "spoof")
REQUIRED_COLUMNS = {"split", "label"}


def create_balanced_manifest(
    manifest_path: Path,
    output_path: Path,
    samples_per_class: int = 1_000,
    seed: int = 42,
) -> dict[tuple[str, str], int]:
    if samples_per_class < 1:
        raise ValueError("samples_per_class must be a positive integer.")
    manifest_path = Path(manifest_path)
    output_path = Path(output_path)
    if not manifest_path.is_file():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    groups: dict[tuple[str, str], list[dict[str, str]]] = {
        (split, label): []
        for split in SPLITS
        for label in LABELS
    }
    with manifest_path.open(newline="", encoding="utf-8") as manifest:
        reader = csv.DictReader(manifest)
        missing_columns = REQUIRED_COLUMNS - set(reader.fieldnames or [])
        if missing_columns:
            raise ValueError(
                "Manifest is missing required columns: "
                + ", ".join(sorted(missing_columns))
            )
        fieldnames = reader.fieldnames or []
        for row in reader:
            key = (row["split"], row["label"].strip().lower())
            if key in groups:
                groups[key].append(row)

    too_small = {
        key: len(rows)
        for key, rows in groups.items()
        if len(rows) < samples_per_class
    }
    if too_small:
        details = ", ".join(
            f"{split}/{label}: {count}"
            for (split, label), count in sorted(too_small.items())
        )
        raise ValueError(
            f"Not enough rows for {samples_per_class} per class: {details}"
        )

    generator = random.Random(seed)
    selected = [
        row
        for key in groups
        for row in generator.sample(groups[key], samples_per_class)
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", newline="", encoding="utf-8") as output:
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(selected)

    return {key: samples_per_class for key in groups}


def _positive_int(value: str) -> int:
    parsed = int(value)
    if parsed < 1:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return parsed


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Sample the same number of bonafide and spoof recordings from "
            "each ASVspoof split."
        )
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=project_root / "data" / "manifests" / "asvspoof2019_la.csv",
        help="Input manifest generated by prepare_asvspoof_manifest.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=project_root
        / "data"
        / "manifests"
        / "asvspoof2019_la_balanced_1000_seed42.csv",
        help="Output path for the balanced manifest.",
    )
    parser.add_argument(
        "--samples-per-class",
        type=_positive_int,
        default=1_000,
        help="Number of samples per label in each split.",
    )
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    counts = create_balanced_manifest(
        args.manifest,
        args.output,
        samples_per_class=args.samples_per_class,
        seed=args.seed,
    )
    print(f"Balanced manifest written to {args.output}")
    for (split, label), count in counts.items():
        print(f"{split}/{label}: {count}")
    print(f"total: {sum(counts.values())} samples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
